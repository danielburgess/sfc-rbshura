#!/usr/bin/env python3
"""
Build a 2bpp SNES font for Rushing Beat Shura English translation.
Generates en_font.bin (15,808 bytes) and en_font_preview.ppm.

Each character is 16x16 pixels stored as 4 sequential 8x8 2bpp SNES tiles
(top-left, top-right, bottom-left, bottom-right).

2bpp tile format: 8 rows x 2 bytes/row = 16 bytes/tile.
  For each row: byte0 = bitplane 0, byte1 = bitplane 1.
  Pixel 0 is bit 7 (leftmost).

Pixel values: 0 = transparent, 3 = lit (both bitplanes set).
"""

import struct
import os

TOTAL_CHARS = 247  # $00-$F6
CHAR_SIZE = 64     # 4 tiles x 16 bytes each
TOTAL_BYTES = TOTAL_CHARS * CHAR_SIZE  # 15808

# ---------------------------------------------------------------------------
# Glyph definitions: 16 rows of 16 chars each. '.' = 0, '#' = 3
# ---------------------------------------------------------------------------

def g(rows):
    """Pad/trim a glyph definition to exactly 16 rows of 16 columns."""
    out = []
    for r in rows:
        r = r.ljust(16, '.')[:16]
        out.append(r)
    while len(out) < 16:
        out.append('.' * 16)
    return out

