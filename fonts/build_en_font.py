ACCENT_CEDILLA_LOWER = [
    '......##........',
    '.....##.........',
]

def apply_accent(base_glyph, accent_rows, accent_start_row=1):
    """Overlay accent marks at the top of a glyph."""
    result = [row[:] for row in base_glyph]  # deep copy of list of strings
    result = list(result)
    for i, arow in enumerate(accent_rows):
        r = accent_start_row + i
        if r < 0 or r >= 16:
            continue
        new_row = list(result[r])
        for c in range(16):
            if c < len(arow) and arow[c] == '#':
                new_row[c] = '#'
        result[r] = ''.join(new_row)
    return result

def apply_cedilla(base_glyph):
    """Add cedilla below the character."""
    result = list(base_glyph)
    for i, crow in enumerate(ACCENT_CEDILLA_LOWER):
        r = 13 + i
        if r >= 16:
            continue
        new_row = list(result[r])
        for c in range(16):
            if c < len(crow) and crow[c] == '#':
                new_row[c] = '#'
        result[r] = ''.join(new_row)
    return result

def make_accented_upper(base_glyph, accent_rows):
    """For uppercase: shift base down by 1 row to make room for accent at rows 1-2."""
    # Shift base: remove row 1 (first empty row after row 0) content effectively
    # We keep the base starting from its first content row and place accent above
    shifted = list(base_glyph)
    return apply_accent(shifted, accent_rows, accent_start_row=0)

def make_accented_lower(base_glyph, accent_rows):
    """For lowercase: place accent at rows 2-3 (where the blank area is)."""
    return apply_accent(base_glyph, accent_rows, accent_start_row=2)


