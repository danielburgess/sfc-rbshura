char_map[0x97] = make_accented_lower(GLYPH_y, ACCENT_DIAERESIS)


# ---------------------------------------------------------------------------
# Convert 16x16 pixel grid to SNES 2bpp tiles
# ---------------------------------------------------------------------------

def glyph_to_pixels(glyph):
    """Convert glyph string grid to 16x16 pixel array (0 or 3)."""
    pixels = []
    for row_str in glyph:
        row = []
        for ch in row_str:
            row.append(3 if ch == '#' else 0)
        pixels.append(row)
    return pixels

def encode_8x8_tile_2bpp(pixels_8x8):
    """
    Encode an 8x8 pixel block as 16 bytes of SNES 2bpp tile data.
    Each row: byte0 = bitplane 0, byte1 = bitplane 1.
    Pixel 0 is bit 7 (leftmost).
    """
    data = bytearray(16)
    for y in range(8):
        bp0 = 0
        bp1 = 0
        for x in range(8):
            px = pixels_8x8[y][x]
            if px & 1:
                bp0 |= (0x80 >> x)
            if px & 2:
                bp1 |= (0x80 >> x)
        data[y * 2] = bp0
        data[y * 2 + 1] = bp1
    return bytes(data)

def encode_16x16_char(glyph):
    """
    Encode a 16x16 glyph as 4 sequential 8x8 2bpp tiles:
    top-left, top-right, bottom-left, bottom-right.
    Returns 64 bytes.
    """
    pixels = glyph_to_pixels(glyph)

    # Extract 4 quadrants
    tl = [row[0:8] for row in pixels[0:8]]
    tr = [row[8:16] for row in pixels[0:8]]
    bl = [row[0:8] for row in pixels[8:16]]
    br = [row[8:16] for row in pixels[8:16]]

    return (encode_8x8_tile_2bpp(tl) +
            encode_8x8_tile_2bpp(tr) +
            encode_8x8_tile_2bpp(bl) +
            encode_8x8_tile_2bpp(br))


# ---------------------------------------------------------------------------
# Build binary
# ---------------------------------------------------------------------------

def build_font_binary():
    data = bytearray()
    for code in range(TOTAL_CHARS):
        glyph = char_map.get(code, BLANK)
        data.extend(encode_16x16_char(glyph))
    assert len(data) == TOTAL_BYTES, f"Expected {TOTAL_BYTES} bytes, got {len(data)}"
    return bytes(data)


# ---------------------------------------------------------------------------
# PPM preview
# ---------------------------------------------------------------------------

def build_preview_ppm(output_path):
    """
    Generate a PPM visualization grid of the font.
    16 characters per row, ceil(247/16) = 16 rows.
    Each character cell is 16x16 pixels + 1px border = 17x17.
    """
    cols = 16
    rows = (TOTAL_CHARS + cols - 1) // cols  # 16

    cell_w = 18  # 16px + 2px spacing
    cell_h = 18
    img_w = cols * cell_w + 2
    img_h = rows * cell_h + 2

    # RGB pixel buffer - dark background
    img = bytearray(img_w * img_h * 3)
    bg_r, bg_g, bg_b = 32, 32, 48  # dark blue-grey background
    grid_r, grid_g, grid_b = 64, 64, 80  # grid lines
    fg_r, fg_g, fg_b = 240, 240, 255  # white-ish foreground

    # Fill background
    for i in range(img_w * img_h):
        img[i*3] = bg_r
        img[i*3+1] = bg_g
        img[i*3+2] = bg_b

    # Draw characters
    for code in range(TOTAL_CHARS):
        glyph = char_map.get(code, BLANK)
        pixels = glyph_to_pixels(glyph)

        grid_col = code % cols
        grid_row = code // cols

        ox = 1 + grid_col * cell_w
        oy = 1 + grid_row * cell_h

        for py in range(16):
            for px in range(16):
                ix = ox + px
                iy = oy + py
                idx = (iy * img_w + ix) * 3
                if pixels[py][px] == 3:
                    img[idx] = fg_r
                    img[idx+1] = fg_g
                    img[idx+2] = fg_b

    # Draw grid lines
    for grid_row in range(rows + 1):
        y = grid_row * cell_h
        if y < img_h:
            for x in range(img_w):
                idx = (y * img_w + x) * 3
                img[idx] = grid_r
                img[idx+1] = grid_g
                img[idx+2] = grid_b

    for grid_col in range(cols + 1):
        x = grid_col * cell_w
        if x < img_w:
            for y in range(img_h):
                idx = (y * img_w + x) * 3
                img[idx] = grid_r
                img[idx+1] = grid_g
                img[idx+2] = grid_b

    with open(output_path, 'wb') as f:
        f.write(f"P6\n{img_w} {img_h}\n255\n".encode())
        f.write(img)

    print(f"Preview written to {output_path} ({img_w}x{img_h})")


